export function migrateDemo(state: State, seed: State): State {
  for (const legacy of legacyCustomers) {
    const customer = state.customers.find(
      (c) => c.id === legacy.id && c.name === legacy.name,
    );
    const current = seed.customers.find((c) => c.id === legacy.id);
    if (!customer || !current) continue;
    for (const key of ["short", "industry", "position"] as const) {
      if (customer[key] === legacy[key]) customer[key] = current[key];
    }
  }
  return JSON.parse(JSON.stringify(state), (_key, value) =>
    typeof value === "string"
      ? replacements.reduce(
          (text, [old, next]) => text.replaceAll(old, next),
          value,
        )
      : value,
  );
}
